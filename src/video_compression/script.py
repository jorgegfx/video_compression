import os
import re
from datetime import datetime

from video_compression.state import FileResult

# No comma: unquoted, PowerShell reads it as the array operator and would split
# filter chains such as "hqdn3d=...,scale=...".
_SAFE_TOKEN = re.compile(r"^[A-Za-z0-9_\-.:/\\=+]+$")


def ps_quote(arg: str) -> str:
    """Quote one argument for PowerShell (single quotes: no $ or ` expansion)."""
    if _SAFE_TOKEN.match(arg):
        return arg
    return "'" + arg.replace("'", "''") + "'"


def ps_comment(text: str) -> str:
    return "\n".join(f"# {line}" for line in text.splitlines())


def ps_copy(src: str, dst: str) -> str:
    """Copy src to dst unless dst exists (never overwrite, like ffmpeg -n).

    -ErrorAction Stop ends the script on a failed copy, so ffmpeg never runs on
    a missing or partial file. -LiteralPath: names may contain [ ] wildcards.
    """
    return (
        f"if (-not (Test-Path -LiteralPath {ps_quote(dst)})) "
        f"{{ Copy-Item -LiteralPath {ps_quote(src)} -Destination {ps_quote(dst)} -ErrorAction Stop }}"
    )


def render_ps1(
    results: list[FileResult], output_dir: str, staging_dir: str | None = None
) -> str:
    """Render the script. Paths come in absolute, so it runs from any directory.

    With staging_dir (the --input option), each source is first copied there and
    ffmpeg reads the copy.
    """
    lines = [
        "# ffmpeg commands generated by video-compression",
        f"# {datetime.now():%Y-%m-%d %H:%M}",
        "# Review before running:  powershell -ExecutionPolicy Bypass -File <this file>",
        "",
        f"New-Item -ItemType Directory -Force -Path {ps_quote(output_dir)} | Out-Null",
    ]
    if staging_dir:
        lines.append(f"New-Item -ItemType Directory -Force -Path {ps_quote(staging_dir)} | Out-Null")
    for r in results:
        lines += ["", f"# --- {os.path.basename(r['file'])}"]
        if "reasoning" in r:
            lines.append(ps_comment(r["reasoning"]))
        if r.get("skipped"):
            lines.append("# SKIPPED: already efficient")
        elif "command" in r:
            if "staged_input" in r:
                lines.append(ps_copy(r["file"], r["staged_input"]))
            lines.append(" ".join(ps_quote(a) for a in r["command"]))
        if "error" in r:
            lines.append(ps_comment(f"ERROR: {r['error']}"))
    return "\n".join(lines) + "\n"


def write_ps1(
    results: list[FileResult], output_dir: str, path: str, staging_dir: str | None = None
) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    # utf-8-sig: Windows PowerShell 5.1 needs the BOM to read non-ASCII correctly.
    with open(path, "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write(render_ps1(results, output_dir, staging_dir))
